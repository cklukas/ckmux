# Build the publishable snapshot branch.
#
# The development history stays private. This writes a single snapshot commit
# on `refs/heads/public` holding the current tree minus everything named in
# tools/publish/publicignore, with tools/publish/overrides/* substituted in.
# The first run has no parent, so the published branch begins with no history;
# later runs append one snapshot commit each, so the remote is never rewritten.
#
# Nothing here touches the working tree, the index, or HEAD: the snapshot is
# assembled in a temporary index with plumbing. It is therefore safe to run
# while other work is in progress in this checkout.
#
#   tools/publish/make-public.sh                  # snapshot HEAD onto `public`
#   tools/publish/make-public.sh --dry-run        # list what would be included
#   tools/publish/make-public.sh -m "Release 0.1"
#
# Then, once:  git remote add origin https://github.com/<owner>/<repo>.git
# And to push: git push -u origin public:main

set -eu

root=$(git rev-parse --show-toplevel)
cd "$root"

source_rev=HEAD
branch=public
message=
dry_run=0

while [ $# -gt 0 ]; do
    case $1 in
        --source) source_rev=$2; shift 2 ;;
        --branch) branch=$2; shift 2 ;;
        -m|--message) message=$2; shift 2 ;;
        -n|--dry-run) dry_run=1; shift ;;
        -h|--help) sed -n '5,26p' "$0" | sed 's/^# \{0,1\}//'; exit 0 ;;
        *) echo "make-public: unknown argument: $1" >&2; exit 2 ;;
    esac
done

ignore_file=tools/publish/publicignore
overrides_dir=tools/publish/overrides
[ -f "$ignore_file" ] || { echo "make-public: missing $ignore_file" >&2; exit 1; }

src_commit=$(git rev-parse --verify "$source_rev^{commit}")
[ -n "$message" ] || message="Snapshot of $(git rev-parse --short "$src_commit")"

# A path is excluded when it equals an entry in publicignore, or lies under an
# entry that names a directory. Comments and blank lines are dropped.
filter_paths() {
    awk -v ignore="$ignore_file" '
        BEGIN {
            while ((getline line < ignore) > 0) {
                sub(/[ \t]+$/, "", line)
                if (line == "" || line ~ /^#/) continue
                patterns[++n] = line
            }
        }
        {
            path = $0
            sub(/^[^\t]*\t/, "", path)          # ls-tree: "<mode> <type> <sha>\t<path>"
            for (i = 1; i <= n; i++) {
                p = patterns[i]
                if (substr(p, length(p)) == "/") {
                    if (index(path, p) == 1) next
                } else if (path == p) {
                    next
                }
            }
            print
        }'
}

index=$(mktemp "${TMPDIR:-/tmp}/make-public-index.XXXXXX")
rm -f "$index"                                   # git wants to create it itself
trap 'rm -f "$index"' EXIT INT TERM
export GIT_INDEX_FILE="$index"

all_paths=$(git ls-tree -r --full-tree "$src_commit")
git ls-tree -r --full-tree "$src_commit" | filter_paths | git update-index --index-info

# Overrides: a file at tools/publish/overrides/<path> replaces <path> in the
# snapshot. This is how the public README differs from the working one without
# either copy having to be regenerated by hand.
overrides=
if [ -d "$overrides_dir" ]; then
    overrides=$(cd "$overrides_dir" && find . -type f | sed 's|^\./||' | sort)
    for rel in $overrides; do
        blob=$(git hash-object -w "$overrides_dir/$rel")
        git update-index --add --cacheinfo "100644,$blob,$rel"
    done
fi

kept=$(git ls-files | wc -l | tr -d ' ')
total=$(printf '%s\n' "$all_paths" | wc -l | tr -d ' ')

if [ "$dry_run" -eq 1 ]; then
    echo "source:    $(git rev-parse --short "$src_commit") ($source_rev)"
    echo "branch:    $branch (not written — dry run)"
    echo "included:  $kept of $total tracked paths"
    echo
    echo "excluded:"
    printf '%s\n' "$all_paths" | sed 's/^[^\t]*\t//' | sort > "$index.all"
    git ls-files | sort > "$index.kept"
    comm -23 "$index.all" "$index.kept" | sed 's/^/  - /'
    rm -f "$index.all" "$index.kept"
    [ -n "$overrides" ] && { echo; echo "overridden:"; printf '%s\n' "$overrides" | sed 's/^/  ~ /'; }
    exit 0
fi

tree=$(git write-tree)

if parent=$(git rev-parse -q --verify "refs/heads/$branch"); then
    if [ "$(git rev-parse "$parent^{tree}")" = "$tree" ]; then
        echo "make-public: $branch is already this snapshot — nothing to do."
        exit 0
    fi
    commit=$(git commit-tree "$tree" -p "$parent" -m "$message")
else
    commit=$(git commit-tree "$tree" -m "$message")
fi

git update-ref "refs/heads/$branch" "$commit"

echo "make-public: $branch -> $(git rev-parse --short "$commit")"
echo "  source:   $(git rev-parse --short "$src_commit") ($source_rev)"
echo "  included: $kept of $total tracked paths"
echo "  message:  $message"
echo
echo "Review it with:  git show --stat $branch"
echo "Publish it with: git push origin $branch:main"
